function classic(
  id: string,
  name: string,
  description: string,
  light: Partial<ThemeColors> = {},
  dark: Partial<ThemeColors> = {},
): ThemeDefinition {
  return themeDefinitionSchema.parse({
    formatVersion: 1,
    id: `builtin.${id}`,
    name,
    version: '1.0.0',
    author: '嵌入式刷题本',
    description,
    license: '应用内置视觉预设',
    light: { ...forestLight, ...light, focus: light.accent ?? forestLight.accent },
    dark: { ...forestDark, ...dark, focus: dark.accent ?? forestDark.accent },
    presentation: { font: 'system', radius: 'rounded', density: 'comfortable', layout: 'classic' },
  })
}

